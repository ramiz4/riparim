export function selectSuites(group = "all", registry = registeredSuites) {
  if (!["all", "core", "node"].includes(group))
    throw Error(`Unknown test group: ${group}`);
  const seen = new Set();
  for (const { file, group: suiteGroup } of registry) {
    if (!["core", "node"].includes(suiteGroup))
      throw Error(`Invalid suite group: ${suiteGroup}`);
    if (seen.has(file)) throw Error(`Duplicate suite: ${file}`);
    seen.add(file);
  }
  return registry
    .filter((suite) => group === "all" || suite.group === group)
    .map(({ file }) => file);
}
